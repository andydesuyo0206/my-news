@app.route('/')
def index():
    news = get_all_news()
    now = datetime.now(JST)
    return render_template(
        'index.html',
        news=news,
        kotoba=get_kotoba(),
        shunshuu=get_shunshuu(news),
        now=now,
        weekday=WEEKDAY_JP[now.weekday()],
        last_updated=datetime.fromtimestamp(_cache_ts, JST).strftime('%H:%M') if _cache_ts else '—',
    )


